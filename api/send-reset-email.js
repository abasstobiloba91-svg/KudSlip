// =========================================================
// API ROUTE: /api/send-reset-email
// =========================================================
import { createClient } from '@supabase/supabase-js';
import { Resend } from 'resend';

// Initialize Resend with your API Key
// Make sure RESEND_API_KEY is in your .env file
const resend = new Resend(process.env.RESEND_API_KEY);

// Initialize Supabase with the SERVICE ROLE KEY (Bypasses RLS to generate auth links)
// Make sure SUPABASE_SERVICE_ROLE_KEY is in your .env file
const supabaseAdmin = createClient(
  process.env.VITE_SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY
);

export default async function handler(req, res) {
  // Only allow POST requests
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method Not Allowed' });
  }

  const { email } = req.body;

  if (!email) {
    return res.status(400).json({ error: 'Email is required' });
  }

  try {
    // 1. Generate the secure reset link using Supabase Admin
    const { data, error } = await supabaseAdmin.auth.admin.generateLink({
      type: 'recovery',
      email: email,
    });

    if (error) throw error;

    // The raw link generated by Supabase
    // Note: You can append this to your custom frontend URL if needed
    const resetLink = data.properties.action_link;

    // 2. Send the premium white-labeled email using Resend
    const emailResponse = await resend.emails.send({
      from: 'KudiSlip Support <support@kudislip.com>', // MUST match your verified domain in Resend!
      to: [email],
      subject: 'Reset Your KudiSlip Password',
      html: `
        <div style="font-family: 'Helvetica Neue', Helvetica, Arial, sans-serif; background-color: #F8FAFC; padding: 60px 20px; text-align: center;">
          <div style="max-width: 500px; margin: 0 auto; background-color: #FFFFFF; border-radius: 16px; padding: 40px; box-shadow: 0 10px 25px -5px rgba(0, 0, 0, 0.05); border: 1px solid #E2E8F0; text-align: left;">
            
            <div style="text-align: center; margin-bottom: 32px;">
              <img src="https://kudislip.com/logo.png" alt="KudiSlip Logo" style="height: 48px; object-fit: contain;" />
            </div>

            <h2 style="color: #0F172A; font-size: 24px; font-weight: 800; margin-top: 0; margin-bottom: 16px; text-align: center;">
              Reset Your Password
            </h2>

            <p style="color: #64748B; font-size: 16px; line-height: 1.6; margin-bottom: 32px; text-align: center;">
              We received a request to unlock your KudiSlip command center. Click the button below to securely set a new password and regain access.
            </p>

            <div style="text-align: center;">
              <a href="${resetLink}" style="display: inline-block; background-color: #8B5CF6; color: #FFFFFF; padding: 16px 32px; border-radius: 12px; font-weight: 800; text-decoration: none; font-size: 16px;">
                Securely Reset Password
              </a>
            </div>

            <div style="border-top: 1px solid #E2E8F0; margin-top: 32px; padding-top: 24px;">
              <p style="color: #94A3B8; font-size: 13px; line-height: 1.5; margin: 0; text-align: center;">
                If you didn't request this, you can safely ignore this email. Your KudiSlip account remains completely secure.
              </p>
            </div>
          </div>
          
          <div style="margin-top: 32px; color: #94A3B8; font-size: 12px; font-weight: 700; text-align: center; text-transform: uppercase; letter-spacing: 1px;">
            &copy; ${new Date().getFullYear()} KudiSlip. The Ultimate Revenue Engine.
          </div>
        </div>
      `
    });

    return res.status(200).json({ success: true, emailResponse });

  } catch (error) {
    console.error("Reset Email Error:", error);
    return res.status(500).json({ error: error.message || "An unexpected error occurred" });
  }
}
